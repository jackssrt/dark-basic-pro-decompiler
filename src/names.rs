/// Camel-case export stem to upper-cased DBP keyword, for the commands with no
/// recorded spelling.
pub fn camel(name: &str) -> String {
    let bytes: Vec<char> = name.chars().collect();
    let mut out = String::with_capacity(name.len() + 4);
    for (i, &c) in bytes.iter().enumerate() {
        if i > 0 && c.is_uppercase() {
            let prev = bytes[i - 1];
            let next_is_lower = bytes.get(i + 1).is_some_and(|n| n.is_lowercase());
            if prev.is_lowercase()
                || prev.is_ascii_digit()
                || (prev.is_uppercase() && next_is_lower)
            {
                out.push(' ');
            }
        }
        out.extend(c.to_uppercase());
    }
    out
}

/// The DBP keyword for a DLL export name, case-insensitively.
pub fn keyword(export: &str) -> String {
    KEYWORDS
        .iter()
        .find(|(k, _)| k.eq_ignore_ascii_case(export))
        .map_or_else(|| camel(export), |(_, v)| (*v).to_string())
}
